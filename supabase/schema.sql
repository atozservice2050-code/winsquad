create or replace function public.sync_round_stats()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.round_stats (round_id, round_no, total_bids, player_count, ends_at, status)
  values (new.id, new.round_no, new.total_bids, new.player_count, new.ends_at, new.status)
  on conflict (round_id) do update set
    round_no     = excluded.round_no,
    total_bids   = excluded.total_bids,
    player_count = excluded.player_count,
    ends_at      = excluded.ends_at,
    status       = excluded.status,
    updated_at   = now();
  return new;
end;
$$;

drop trigger if exists trg_rounds_sync_stats on public.rounds;
create trigger trg_rounds_sync_stats
  after insert or update on public.rounds
  for each row execute function public.sync_round_stats();

create or replace function public.bump_round_totals()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.rounds
  set total_bids   = total_bids + new.amount,
      player_count = player_count + 1,
      updated_at   = now()
  where id = new.round_id;
  return new;
end;
$$;

