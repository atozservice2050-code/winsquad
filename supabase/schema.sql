-- Peer-to-peer transfer. Rules: amount > 0, <= 50% of sender's balance,
-- recipient found by 14-digit transfer_id, and the sender must not have
-- completed any transfer_in/transfer_out in the last 7 days (once per week).
create or replace function public.transfer_funds(
  p_to_transfer_id text,
  p_amount         numeric
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid   uuid := auth.uid();
  v_to    uuid;
  v_bal   numeric(12,2);
  v_first uuid;
  v_second uuid;
begin
  if v_uid is null then
    return jsonb_build_object('ok', false, 'error', 'not authenticated');
  end if;

  p_amount := round(p_amount, 2);
  if p_amount is null or p_amount <= 0 then
    return jsonb_build_object('ok', false, 'error', 'invalid amount');
  end if;

  select id into v_to from public.profiles where transfer_id = p_to_transfer_id;
  if v_to is null then
    return jsonb_build_object('ok', false, 'error', 'recipient not found');
  end if;
  if v_to = v_uid then
    return jsonb_build_object('ok', false, 'error', 'cannot transfer to yourself');
  end if;

  -- lock both wallets in a stable order to avoid deadlocks
  if v_uid < v_to then
    v_first := v_uid; v_second := v_to;
  else
    v_first := v_to;  v_second := v_uid;
  end if;
  perform 1 from public.wallets where user_id = v_first  for update;
  perform 1 from public.wallets where user_id = v_second for update;

  select balance into v_bal from public.wallets where user_id = v_uid;
  if v_bal is null or v_bal < p_amount then
    return jsonb_build_object('ok', false, 'error', 'insufficient balance');
  end if;
  if p_amount > v_bal * 0.5 then
    return jsonb_build_object('ok', false, 'error', 'amount exceeds 50% of balance');
  end if;

  if exists (
    select 1 from public.transactions
    where user_id = v_uid
      and type in ('transfer_in', 'transfer_out')
      and status = 'completed'
      and created_at > now() - interval '7 days'
  ) then
    return jsonb_build_object('ok', false, 'error', 'transfer limit: one transfer per week');
  end if;

  update public.wallets
  set balance = balance - p_amount, updated_at = now()
  where user_id = v_uid;
  update public.wallets
  set balance = balance + p_amount, updated_at = now()
  where user_id = v_to;

  insert into public.transactions (user_id, type, amount, status, counterparty_user_id, note)
  values (v_uid, 'transfer_out', p_amount, 'completed', v_to,
          'Transfer to ID ' || p_to_transfer_id);
  insert into public.transactions (user_id, type, amount, status, counterparty_user_id, note)
  values (v_to, 'transfer_in', p_amount, 'completed', v_uid,
          'Transfer received');

  return jsonb_build_object('ok', true, 'amount', p_amount);
end;
$$;

-- Daily streak: once per PKT calendar day. Consecutive days increment,
-- a missed day resets to 1. Reward = Rs 10 * day, capped at day 7
-- (10, 20, 30, 40, 50, 60, 70, 70, ...).
create or replace function public.claim_daily_streak()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid    uuid := auth.uid();
  v_today  date := (now() at time zone 'Asia/Karachi')::date;
  v_streak int;
  v_last   date;
  v_day    int;
  v_amount numeric(12,2);
begin
  if v_uid is null then
    return jsonb_build_object('ok', false, 'error', 'not authenticated');
  end if;

  select current_streak, last_claim_date into v_streak, v_last
  from public.streaks
  where user_id = v_uid
  for update;

  if v_last = v_today then
    return jsonb_build_object('ok', false, 'error', 'already claimed today');
  end if;

  if v_last = v_today - 1 then
    v_streak := coalesce(v_streak, 0) + 1;
  else
    v_streak := 1;
  end if;

  v_day    := least(v_streak, 7);
  v_amount := (10 * v_day)::numeric(12,2);

  insert into public.streaks (user_id, current_streak, last_claim_date)
  values (v_uid, v_streak, v_today)
  on conflict (user_id) do update
    set current_streak = v_streak, last_claim_date = v_today;

  update public.wallets
  set balance = balance + v_amount, updated_at = now()
  where user_id = v_uid;

  insert into public.rewards (user_id, type, amount, meta)
  values (v_uid, 'streak', v_amount,
          jsonb_build_object('streak_day', v_day, 'streak_total', v_streak));
  insert into public.transactions (user_id, type, amount, status, note)
  values (v_uid, 'bonus', v_amount, 'completed',
          'Daily streak day ' || v_day);

  return jsonb_build_object('ok', true, 'streak_day', v_day, 'amount', v_amount);
end;
$$;

-- Apply a referral code once per account. Both referrer and referee get Rs 100.
create or replace function public.apply_referral(p_referral_id text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid      uuid := auth.uid();
  v_referrer uuid;
  v_bonus    constant numeric(12,2) := 100;
