-- Join a private table by invite code (case/format tolerant). Fills the next
-- free seat (1-4). Table becomes 'active' when the 2nd seat fills (029).
create or replace function public.join_private_table(p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid  uuid := auth.uid();
  v_norm text;
  v_tbl  public.private_tables%rowtype;
  v_seat smallint;
  v_n    int;
begin
  if v_uid is null then
    return jsonb_build_object('ok', false, 'error', 'not authenticated');
  end if;
  if p_code is null or trim(p_code) = '' then
    return jsonb_build_object('ok', false, 'error', 'invite code required');
  end if;

  v_norm := upper(regexp_replace(p_code, '[^A-Z0-9]', '', 'gi'));

  select t.* into v_tbl
  from public.private_tables t
  where replace(t.code, '-', '') = v_norm
    and t.status in ('waiting', 'active')
  limit 1;

  if v_tbl.id is null then
    return jsonb_build_object('ok', false, 'error', 'table not found or closed');
  end if;

  -- idempotent re-join
  select seat_no into v_seat
  from public.private_seats
  where table_id = v_tbl.id and user_id = v_uid;
  if found then
    return jsonb_build_object('ok', true, 'table_id', v_tbl.id,
                              'seat_no', v_seat, 'already_seated', true,
                              'status', v_tbl.status);
  end if;

  -- serialize seat fills
  select * into v_tbl from public.private_tables where id = v_tbl.id for update;

  select count(*) into v_n from public.private_seats where table_id = v_tbl.id;
  if v_n >= 4 then
    return jsonb_build_object('ok', false, 'error', 'table is full');
  end if;

  select s into v_seat
  from generate_series(1, 4) s
  where not exists (
    select 1 from public.private_seats ps
    where ps.table_id = v_tbl.id and ps.seat_no = s
  )
  order by s
  limit 1;

  insert into public.private_seats (table_id, user_id, seat_no)
  values (v_tbl.id, v_uid, v_seat);

  if v_n + 1 >= 2 then
    update public.private_tables set status = 'active' where id = v_tbl.id;
    v_tbl.status := 'active';
  end if;

  return jsonb_build_object('ok', true, 'table_id', v_tbl.id,
                            'seat_no', v_seat, 'status', v_tbl.status);
end;
$$;

-- Resolve a private table round once all seated players (min 3) have bid.
-- Single HIGHEST bidder loses (tie: earliest placed_at loses); the other 3
-- split 90% proportionally; 10% fee -> private_tables.fee_amount (HIDDEN).
-- Internal helper, but safe to expose: no-ops unless the round is complete.
create or replace function public.resolve_private_round(p_table_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_tbl      public.private_tables%rowtype;
  v_rno      int;
  v_n        int;
  v_pending  int;
  v_loser_id uuid;
  v_loser_amt numeric(12,2);
  v_bid      record;
  v_wtot     numeric(12,2);
  v_fee      numeric(12,2);
  v_dist     numeric(12,2);
  v_payout   numeric(12,2);
  v_paid     numeric(12,2) := 0;
  v_winners  int := 0;
begin
  if p_table_id is null then
    return jsonb_build_object('ok', false, 'error', 'table id required');
  end if;

  perform pg_advisory_xact_lock(hashtext('winsquad_priv_' || p_table_id::text));

  select * into v_tbl from public.private_tables where id = p_table_id for update;
  if v_tbl.id is null then
    return jsonb_build_object('ok', false, 'error', 'table not found');
  end if;
  v_rno := v_tbl.current_round_no;

  select count(*) into v_n
  from public.private_bids
  where table_id = p_table_id and round_no = v_rno;

  -- Seated players who have not bid yet are still pending. A bid from a
  -- player who has since left still counts toward the round (migration 028).
  select count(*) into v_pending
  from public.private_seats s
  where s.table_id = p_table_id
    and not exists (
      select 1 from public.private_bids b
      where b.table_id = p_table_id and b.round_no = v_rno and b.user_id = s.user_id
    );

  if v_n < 2 or v_pending > 0 then
    return jsonb_build_object('ok', true, 'waiting', true,
                              'bids', v_n, 'round_no', v_rno);
  end if;

  -- single highest loses; tie-break: earliest placed_at loses
  select user_id, amount into v_loser_id, v_loser_amt
  from public.private_bids
  where table_id = p_table_id and round_no = v_rno
  order by amount desc, placed_at asc
  limit 1;

  v_fee  := floor(v_loser_amt * 0.10 * 100) / 100;
  v_dist := v_loser_amt - v_fee;

  select sum(amount) into v_wtot
  from public.private_bids
  where table_id = p_table_id and round_no = v_rno and user_id <> v_loser_id;

  for v_bid in
    select user_id, amount
    from public.private_bids
    where table_id = p_table_id and round_no = v_rno and user_id <> v_loser_id
    order by placed_at asc
  loop
    v_payout := floor((v_dist * v_bid.amount / v_wtot) * 100) / 100;
    v_paid   := v_paid + v_payout;
    v_winners := v_winners + 1;

    update public.wallets
    set balance = balance + v_payout, updated_at = now()
    where user_id = v_bid.user_id;

    insert into public.transactions (user_id, type, amount, status, note)
    values (v_bid.user_id, 'payout', v_payout, 'completed',
            'Private table winnings (round ' || v_rno || ')');
  end loop;

  update public.private_tables
  set current_round_no = current_round_no + 1,
      fee_amount = fee_amount + v_fee + (v_dist - v_paid)  -- dust -> house, HIDDEN
  where id = p_table_id;

  return jsonb_build_object(
    'ok', true,
    'resolved', true,
    'round_no', v_rno,
    'winners', v_winners,
    'losers_pool', v_loser_amt,
    'total_payout', v_paid
  );
end;
$$;

-- Place a private bid (min Rs 500). When all seated players have bid, the round
-- resolves automatically via resolve_private_round().
create or replace function public.place_private_bid(
  p_table_id uuid,
  p_amount   numeric
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid    uuid := auth.uid();
  v_tbl    public.private_tables%rowtype;
  v_bid_id uuid;
  v_seats  int;
begin
  if v_uid is null then
    return jsonb_build_object('ok', false, 'error', 'not authenticated');
  end if;

  p_amount := round(p_amount, 2);
  if p_amount is null or p_amount < 50 then
    return jsonb_build_object('ok', false, 'error', 'minimum bid is Rs 50');
  end if;
  if p_amount > 10000 then
    return jsonb_build_object('ok', false, 'error', 'maximum bid is Rs 10,000');
  end if;

  select * into v_tbl from public.private_tables where id = p_table_id for update;
  if v_tbl.id is null then
    return jsonb_build_object('ok', false, 'error', 'table not found');
  end if;
  if v_tbl.status = 'closed' then
    return jsonb_build_object('ok', false, 'error', 'table is closed');
  end if;

  select count(*) into v_seats
  from public.private_seats
  where table_id = p_table_id;

  if v_seats < 2 then
    return jsonb_build_object('ok', false, 'error', 'Need 2 players seated to start the table');
  end if;

  if v_tbl.status <> 'active' then
    update public.private_tables set status = 'active' where id = p_table_id;
    v_tbl.status := 'active';
  end if;

  if not exists (
    select 1 from public.private_seats
    where table_id = p_table_id and user_id = v_uid
  ) then
    return jsonb_build_object('ok', false, 'error', 'you are not seated at this table');
  end if;

  if exists (
    select 1 from public.private_bids
    where table_id = p_table_id and round_no = v_tbl.current_round_no and user_id = v_uid
  ) then
    return jsonb_build_object('ok', false, 'error', 'already placed a bid this round');
  end if;

  update public.wallets
  set balance = balance - p_amount, updated_at = now()
  where user_id = v_uid and balance >= p_amount;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'insufficient balance');
  end if;

  insert into public.transactions (user_id, type, amount, status, note)
  values (v_uid, 'stake', p_amount, 'completed',
          'Private table bid (round ' || v_tbl.current_round_no || ')');

  insert into public.private_bids (table_id, round_no, user_id, amount)
  values (p_table_id, v_tbl.current_round_no, v_uid, p_amount)
  returning id into v_bid_id;

  -- NO auto-resolve: the round waits for the spin turn (spin_private_table).
  return jsonb_build_object(
    'ok', true,
    'bid_id', v_bid_id,
    'amount', p_amount,
    'round_no', v_tbl.current_round_no,
    'resolved', false
  );
exception
  when unique_violation then
    return jsonb_build_object('ok', false, 'error', 'already placed a bid this round');
end;
$$;

create or replace function public.spin_private_table(
  p_table_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid       uuid := auth.uid();
  v_tbl       public.private_tables%rowtype;
  v_seated    uuid[];
  v_spinner   uuid;
  v_pending   int;
  v_bid_count int;
  v_res       jsonb;
begin
  if v_uid is null then
    return jsonb_build_object('ok', false, 'error', 'not authenticated');
  end if;

  select * into v_tbl from public.private_tables where id = p_table_id for update;
  if v_tbl.id is null then
    return jsonb_build_object('ok', false, 'error', 'table not found');
  end if;
  if v_tbl.status = 'closed' then
    return jsonb_build_object('ok', false, 'error', 'table is closed');
  end if;

  if not exists (
    select 1 from public.private_seats
    where table_id = p_table_id and user_id = v_uid
  ) then
    return jsonb_build_object('ok', false, 'error', 'you are not seated at this table');
  end if;

  select array_agg(user_id order by seat_no) into v_seated
  from public.private_seats
  where table_id = p_table_id;

  if coalesce(array_length(v_seated, 1), 0) < 2 then
    return jsonb_build_object('ok', false, 'error', 'Need 2 players seated to spin');
  end if;

  select count(*) into v_pending
  from public.private_seats s
  where s.table_id = p_table_id
    and not exists (
      select 1 from public.private_bids b
      where b.table_id = p_table_id
        and b.round_no = v_tbl.current_round_no
        and b.user_id = s.user_id
    );

  select count(*) into v_bid_count
  from public.private_bids
  where table_id = p_table_id and round_no = v_tbl.current_round_no;

  if v_pending > 0 or v_bid_count < 2 then
    return jsonb_build_object('ok', false, 'error', 'Round is not ready — waiting for all players to bid');
  end if;

  -- spin turn rotates by round over the seated players in seat order
  v_spinner := v_seated[((v_tbl.current_round_no - 1) % array_length(v_seated, 1)) + 1];
  if v_uid <> v_spinner then
    return jsonb_build_object('ok', false, 'error', 'not your turn to spin');
  end if;

  v_res := public.resolve_private_round(p_table_id);
  if not coalesce((v_res ->> 'resolved')::boolean, false) then
    return jsonb_build_object('ok', false, 'error', 'round could not be resolved');
  end if;

  return jsonb_build_object(
    'ok', true,
    'resolved', true,
    'round_no', v_tbl.current_round_no
  );
end;
$$;

create or replace function public.leave_private_table(
  p_table_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid         uuid := auth.uid();
  v_tbl         public.private_tables%rowtype;
  v_seats_left  int;
  v_bid_count   int;
  v_round_total numeric;
  v_bid         public.private_bids%rowtype;
begin
  if v_uid is null then
    return jsonb_build_object('ok', false, 'error', 'not authenticated');
  end if;

  select * into v_tbl from public.private_tables where id = p_table_id for update;
  if v_tbl.id is null then
    return jsonb_build_object('ok', false, 'error', 'table not found');
  end if;

  if not exists (
    select 1 from public.private_seats
    where table_id = p_table_id and user_id = v_uid
  ) then
    return jsonb_build_object('ok', false, 'error', 'you are not seated at this table');
  end if;

  select count(*), coalesce(sum(amount), 0) into v_bid_count, v_round_total
  from public.private_bids
  where table_id = p_table_id and round_no = v_tbl.current_round_no;

  delete from public.private_seats
  where table_id = p_table_id and user_id = v_uid;

  select count(*) into v_seats_left
  from public.private_seats
  where table_id = p_table_id;

  if v_seats_left = 0 then
    -- LAST PLAYER OUT (owner rule): no refunds — the current round's bids
    -- go to the house fee and the table closes.
    update public.private_tables
    set status = 'closed',
        fee_amount = fee_amount + v_round_total
    where id = p_table_id;
  else
    if v_seats_left = 1 and v_bid_count = 1 then
      -- The round can never complete (one player left, one bid): refund
      -- that bid and clear it so the money is not stuck.
      for v_bid in
        select * from public.private_bids
        where table_id = p_table_id and round_no = v_tbl.current_round_no
      loop
        update public.wallets
        set balance = balance + v_bid.amount, updated_at = now()
        where user_id = v_bid.user_id;
        insert into public.transactions (user_id, type, amount, status, note)
        values (v_bid.user_id, 'refund', v_bid.amount, 'completed',
                'Private table round refund');
      end loop;
      delete from public.private_bids
      where table_id = p_table_id and round_no = v_tbl.current_round_no;
    end if;

    update public.private_tables
    set status = case when v_seats_left < 2 then 'waiting' else status end
    where id = p_table_id;
  end if;

  return jsonb_build_object(
    'ok', true,
    'seats_left', v_seats_left,
    'status', case
                when v_seats_left = 0 then 'closed'
                when v_seats_left < 2 then 'waiting'
                else v_tbl.status
              end
  );
end;
$$;

