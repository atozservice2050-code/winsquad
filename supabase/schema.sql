-- One row per app user. Auto-created by the auth.users trigger below.
create table public.profiles (
  id            uuid primary key references auth.users(id) on delete cascade,
  phone         text unique,
  display_name  text not null default 'Player',
  referral_id   text unique,   -- 'WS-######', generated by trigger
  transfer_id   text unique,   -- exactly 14 digits, generated by trigger
  referred_by   uuid references public.profiles(id) on delete set null,
  created_at    timestamptz not null default now(),
  last_seen_at  timestamptz          -- presence heartbeat (migration 033)
);

create table public.wallets (
  user_id    uuid primary key references public.profiles(id) on delete cascade,
  balance    numeric(12,2) not null default 0 check (balance >= 0),
  updated_at timestamptz not null default now()
);

-- Money ledger. Every wallet movement must have a row here.
create table public.transactions (
  id                   uuid primary key default gen_random_uuid(),
  user_id              uuid not null references public.profiles(id) on delete cascade,
  type                 text not null
                         check (type in ('deposit','withdraw','transfer_in','transfer_out',
                                          'stake','payout','bonus','fee',
                                          'coinflip_bet','coinflip_win','coinflip_loss',
                                          'dragontiger_bet','dragontiger_win','dragontiger_loss',
                                          'andarbahar_bet','andarbahar_win',
                                          'roulette_bet','roulette_win','roulette_loss',
                                          'squad_loss',
                                          'cv_bet','cv_win','cv_loss',
                                          'dice_bet','dice_win','dice_loss',
                                          'refund')),
  amount               numeric(12,2) not null check (amount > 0),
  status               text not null default 'completed'
                         check (status in ('pending','completed','rejected')),
  method               text check (method in ('easypaisa','jazzcash','bank','wallet')),
  external_txn_id      text,  -- user-supplied TRX ID for manual deposits
  counterparty_user_id uuid references public.profiles(id) on delete set null,
  note                 text,
  created_at           timestamptz not null default now()
);

-- Public Squad Stakes rounds. fee_amount is HIDDEN from clients (admin only).
create table public.rounds (
  id           uuid primary key default gen_random_uuid(),
  round_no     integer generated by default as identity,
  starts_at    timestamptz not null default now(),
  ends_at      timestamptz not null,  -- starts_at + 30 seconds
  status       text not null default 'open'
                 check (status in ('open','resolving','closed')),
  total_bids   numeric(12,2) not null default 0,  -- sum of bid amounts
  player_count integer not null default 0,       -- number of bidders
  fee_amount   numeric(12,2) not null default 0, -- 10% company cut, HIDDEN
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  check (ends_at > starts_at)
);

create table public.bids (
  id         uuid primary key default gen_random_uuid(),
  round_id   uuid not null references public.rounds(id) on delete cascade,
  user_id    uuid not null references public.profiles(id) on delete cascade,
  amount     numeric(12,2) not null check (amount > 0),
  is_free    boolean not null default false,  -- Rs 10 daily free bid
  placed_at  timestamptz not null default now(),
  unique (round_id, user_id)  -- one bid per user per round
);

-- Realtime-safe mirror of rounds (no fee column). Maintained by triggers.
-- Clients subscribe to THIS via Realtime, not to rounds/bids.
create table public.round_stats (
  round_id     uuid primary key references public.rounds(id) on delete cascade,
  round_no     integer not null,
  total_bids   numeric(12,2) not null default 0,
  player_count integer not null default 0,
  ends_at      timestamptz not null,
  status       text not null,
  updated_at   timestamptz not null default now()
);

-- Winners only. Written by resolve_round(). Losers are NEVER exposed here.
create table public.round_results (
  round_id   uuid not null references public.rounds(id) on delete cascade,
  user_id    uuid not null references public.profiles(id) on delete cascade,
  bid_amount numeric(12,2) not null,
  payout     numeric(12,2) not null,
  created_at timestamptz not null default now(),
  primary key (round_id, user_id)
);

create table public.private_tables (
  id               uuid primary key default gen_random_uuid(),
  code             text not null unique,  -- human invite code, e.g. 'KX4-9MQ2'
  created_by       uuid not null references public.profiles(id) on delete cascade,
  status           text not null default 'waiting'
                     check (status in ('waiting','active','closed')),
  current_round_no integer not null default 1,
  fee_amount       numeric(12,2) not null default 0,  -- 10% company cut, HIDDEN
  created_at       timestamptz not null default now()
);

create table public.private_seats (
  table_id  uuid not null references public.private_tables(id) on delete cascade,
  user_id   uuid not null references public.profiles(id) on delete cascade,
  seat_no   smallint not null check (seat_no between 1 and 4),
  joined_at timestamptz not null default now(),
  primary key (table_id, seat_no),
  unique (table_id, user_id)
);

create table public.private_bids (
  id         uuid primary key default gen_random_uuid(),
  table_id   uuid not null references public.private_tables(id) on delete cascade,
  round_no   integer not null,
  user_id    uuid not null references public.profiles(id) on delete cascade,
  amount     numeric(12,2) not null check (amount >= 50 and amount <= 10000),
  placed_at  timestamptz not null default now(),
  unique (table_id, round_no, user_id)
);

create table public.rewards (
  id         uuid primary key default gen_random_uuid(),
  user_id    uuid not null references public.profiles(id) on delete cascade,
  type       text not null check (type in ('referral','streak','free_bid')),
  amount     numeric(12,2) not null check (amount >= 0),
  meta       jsonb not null default '{}',
  granted_at timestamptz not null default now()
);

create table public.streaks (
  user_id          uuid primary key references public.profiles(id) on delete cascade,
  current_streak   integer not null default 0,
  last_claim_date  date
);

-- Owner/admin user ids. Insert your own auth.users id after first sign-in.
create table public.admins (
  user_id  uuid primary key references public.profiles(id) on delete cascade,
  added_at timestamptz not null default now()
);

