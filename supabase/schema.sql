-- Returns the currently open 30s round, creating one if none exists.
-- Opportunistically resolves expired rounds first (backstop for pg_cron lag).
create or replace function public.get_current_round()
returns public.public_rounds
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id    uuid;
  v_round public.public_rounds%rowtype;
begin
  perform public.resolve_due_rounds();

  select id into v_id
  from public.rounds
  where status = 'open'
  order by starts_at desc
  limit 1;

  if v_id is null then
    -- serialize round creation across concurrent callers
    perform pg_advisory_xact_lock(hashtext('winsquad_current_round'));
    select id into v_id from public.rounds where status = 'open' limit 1;
    if v_id is null then
      insert into public.rounds (starts_at, ends_at, status)
      values (now(), now() + interval '30 seconds', 'open')
      returning id into v_id;
    end if;
  end if;

  select * into v_round from public.public_rounds where id = v_id;
  if v_round.id is null then
    raise exception 'round vanished unexpectedly';
  end if;
  return v_round;
end;
$$;

-- Place a bid. Presets are 10/50/100; any custom amount > 0 is also allowed.
-- Free bid covers a Rs 10 bid (deducts 0), once per PKT calendar day.
create or replace function public.place_bid(
  p_round_id uuid,
  p_amount   numeric,
  p_is_free  boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid   uuid := auth.uid();
  v_today date := (now() at time zone 'Asia/Karachi')::date;
  v_round public.rounds%rowtype;
  v_bid_id uuid;
begin
  if v_uid is null then
    return jsonb_build_object('ok', false, 'error', 'not authenticated');
  end if;
  if p_round_id is null then
    return jsonb_build_object('ok', false, 'error', 'round id required');
  end if;

  p_amount := round(p_amount, 2);
  if p_amount is null or p_amount <= 0 or p_amount > 1000000 then
    return jsonb_build_object('ok', false, 'error', 'invalid amount');
  end if;

  if p_is_free then
    if p_amount <> 10 then
      return jsonb_build_object('ok', false, 'error', 'free bid must be Rs 10');
    end if;
    if exists (
      select 1 from public.bids
      where user_id = v_uid
        and is_free
        and (placed_at at time zone 'Asia/Karachi')::date = v_today
    ) then
      return jsonb_build_object('ok', false, 'error', 'free bid already used today');
    end if;
  end if;

  -- never bid into an expired round; resolve stragglers first
  perform public.resolve_due_rounds();

  select * into v_round from public.rounds where id = p_round_id for update;
  if v_round.id is null then
    return jsonb_build_object('ok', false, 'error', 'round not found');
  end if;
  if v_round.status <> 'open' or v_round.ends_at <= now() then
    return jsonb_build_object('ok', false, 'error', 'round is closed');
  end if;

  if exists (select 1 from public.bids where round_id = p_round_id and user_id = v_uid) then
    return jsonb_build_object('ok', false, 'error', 'already placed a bid this round');
  end if;

  if not p_is_free then
    -- atomic debit; fails cleanly on insufficient balance
    update public.wallets
    set balance = balance - p_amount, updated_at = now()
    where user_id = v_uid and balance >= p_amount;
    if not found then
      return jsonb_build_object('ok', false, 'error', 'insufficient balance');
    end if;
    insert into public.transactions (user_id, type, amount, status, note)
    values (v_uid, 'stake', p_amount, 'completed',
            'Squad Stakes round #' || v_round.round_no || ' bid');
  else
    insert into public.rewards (user_id, type, amount, meta)
    values (v_uid, 'free_bid', 10,
            jsonb_build_object('round_id', p_round_id));
  end if;

  insert into public.bids (round_id, user_id, amount, is_free)
  values (p_round_id, v_uid, p_amount, p_is_free)
  returning id into v_bid_id;
  -- round_stats totals are bumped by trg_bids_bump_totals.

  return jsonb_build_object(
    'ok', true,
    'bid_id', v_bid_id,
    'amount', p_amount,
    'round_no', v_round.round_no,
    'is_free', p_is_free
  );
exception
  when unique_violation then
    return jsonb_build_object('ok', false, 'error', 'already placed a bid this round');
end;
$$;

-- Resolve a public round. IDEMPOTENT: no-op if already closed.
--   * bids ordered by amount DESC, placed_at ASC -> top 2 LOSE
--     (tie-break: earliest placed_at loses)
--   * losers_pool = sum of top-2 amounts
--   * fee = 10% of losers_pool -> rounds.fee_amount (HIDDEN from clients)
--   * every other bidder wins: payout = 90% pool * (bid / winners_total),
--     floored to 2dp. Rounding dust goes to the house fee.
--   * < 3 bidders: round cancelled, everyone refunded.
create or replace function public.resolve_round(p_round_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_round      public.rounds%rowtype;
  v_bid        record;
  v_rank       int := 0;
  v_n          int := 0;
  v_winners    int := 0;
  v_losers     numeric(12,2) := 0;
  v_loser_ids  uuid[] := '{}';
  v_wtot       numeric(12,2) := 0;
  v_fee        numeric(12,2);
  v_dist       numeric(12,2);
  v_payout     numeric(12,2);
  v_paid       numeric(12,2) := 0;
begin
  if p_round_id is null then
    return jsonb_build_object('ok', false, 'error', 'round id required');
  end if;

  perform pg_advisory_xact_lock(hashtext('winsquad_resolve_' || p_round_id::text));

  update public.rounds
  set status = 'resolving', updated_at = now()
  where id = p_round_id and status = 'open'
  returning * into v_round;

  if not found then
    -- idempotent no-op
    select * into v_round from public.rounds where id = p_round_id;
    if v_round.id is null then
      return jsonb_build_object('ok', false, 'error', 'round not found');
    end if;
    if v_round.status = 'closed' then
      return jsonb_build_object('ok', true, 'already_closed', true,
                                'round_no', v_round.round_no);
    end if;
    return jsonb_build_object('ok', false, 'error', 'round is not open');
  end if;

  select count(*) into v_n from public.bids where round_id = p_round_id;

  if v_n < 3 then
    -- not enough players: refund PAID bids only (free bids staked nothing),
    -- no fee, no winners
    for v_bid in
      select user_id, amount from public.bids
      where round_id = p_round_id and not is_free
    loop
      update public.wallets
      set balance = balance + v_bid.amount, updated_at = now()
      where user_id = v_bid.user_id;
      insert into public.transactions (user_id, type, amount, status, note)
      values (v_bid.user_id, 'payout', v_bid.amount, 'completed',
              'Refund: round #' || v_round.round_no || ' cancelled (not enough players)');
    end loop;
    update public.rounds set status = 'closed', updated_at = now()
    where id = p_round_id;
    return jsonb_build_object('ok', true, 'round_no', v_round.round_no,
                              'cancelled', true, 'refunded', v_n);
  end if;

  -- classify: first 2 rows of (amount DESC, placed_at ASC) lose
  for v_bid in
    select user_id, amount
    from public.bids
    where round_id = p_round_id
    order by amount desc, placed_at asc
  loop
    v_rank := v_rank + 1;
    if v_rank <= 2 then
      v_losers    := v_losers + v_bid.amount;
      v_loser_ids := v_loser_ids || v_bid.user_id;
    else
      v_wtot    := v_wtot + v_bid.amount;
      v_winners := v_winners + 1;
    end if;
  end loop;

  v_fee  := floor(v_losers * 0.10 * 100) / 100;
  v_dist := v_losers - v_fee;

  -- pay winners proportionally (floored to 2dp); write public leaderboard rows
  for v_bid in
    select user_id, amount
    from public.bids
    where round_id = p_round_id
      and not (user_id = any (v_loser_ids))
    order by placed_at asc
  loop
    v_payout := floor((v_dist * v_bid.amount / v_wtot) * 100) / 100;
    v_paid   := v_paid + v_payout;

    update public.wallets
    set balance = balance + v_payout, updated_at = now()
    where user_id = v_bid.user_id;

    insert into public.transactions (user_id, type, amount, status, note)
    values (v_bid.user_id, 'payout', v_payout, 'completed',
            'Squad Stakes round #' || v_round.round_no || ' winnings');

    insert into public.round_results (round_id, user_id, bid_amount, payout)
    values (p_round_id, v_bid.user_id, v_bid.amount, v_payout);
  end loop;

  -- rounding dust goes to the house fee; fee stays HIDDEN on rounds
  update public.rounds
  set status     = 'closed',
      updated_at = now(),
      fee_amount = fee_amount + v_fee + (v_dist - v_paid)
  where id = p_round_id;

  return jsonb_build_object(
    'ok', true,
    'round_no', v_round.round_no,
    'winners', v_winners,
    'losers_pool', v_losers,
    'total_payout', v_paid
  );
end;
$$;

-- Resolve every open round whose window has ended. Called by pg_cron
-- (see header) and opportunistically by get_current_round()/place_bid().
create or replace function public.resolve_due_rounds()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  r       record;
  v_count int := 0;
begin
  for r in
    select id from public.rounds
    where status = 'open' and ends_at <= now()
    order by ends_at asc
  loop
    perform public.resolve_round(r.id);
    v_count := v_count + 1;
  end loop;
  return jsonb_build_object('ok', true, 'resolved', v_count);
end;
$$;

