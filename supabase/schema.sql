-- 'WS-' + 6 random digits, e.g. WS-482731
create or replace function public.generate_referral_id()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v text;
begin
  loop
    v := 'WS-' || (floor(random() * 900000) + 100000)::int::text;
    if not exists (select 1 from public.profiles where referral_id = v) then
      return v;
    end if;
  end loop;
end;
$$;

-- Exactly 14 digits, numeric only, unique. Random — NOT derived from CNIC/phone.
create or replace function public.generate_transfer_id()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v text;
begin
  loop
    v := lpad((floor(random() * 100000000000000))::bigint::text, 14, '0');
    if length(v) = 14
       and v ~ '^[0-9]{14}$'
       and not exists (select 1 from public.profiles where transfer_id = v) then
      return v;
    end if;
  end loop;
end;
$$;

-- 6-char unambiguous invite code formatted as XXX-XXX, e.g. 'KX4-9MQ2'
create or replace function public.gen_table_code()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  chars constant text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';  -- no 0/O, 1/I
  v text := '';
  i int;
begin
  for i in 1..6 loop
    v := v || substr(chars, (floor(random() * length(chars))::int) + 1, 1);
  end loop;
  return substr(v, 1, 3) || '-' || substr(v, 4, 3);
end;
$$;

-- Fill referral_id / transfer_id on profile insert.
create or replace function public.set_profile_ids()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.referral_id is null then
    new.referral_id := public.generate_referral_id();
  end if;
  if new.transfer_id is null then
    new.transfer_id := public.generate_transfer_id();
  end if;
  return new;
end;
$$;

drop trigger if exists trg_profiles_ids on public.profiles;
create trigger trg_profiles_ids
  before insert on public.profiles
  for each row execute function public.set_profile_ids();

