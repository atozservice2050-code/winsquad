-- ============================================================================
-- WinSquad — Supabase backend schema
-- Squad Stakes (public arena) + private tables + wallet + rewards
-- Postgres 15. Run top-to-bottom on a FRESH Supabase project via SQL Editor.
-- ============================================================================
--
-- HOW TO RUN
--   1. Supabase Dashboard > SQL Editor > New query > paste this ENTIRE file > Run.
--      It is idempotent-safe for objects (CREATE OR REPLACE / IF NOT EXISTS
--      where possible), but is designed for a fresh project.
--   2. Enable the pg_cron extension (Database > Extensions > pg_cron), then run:
--        select cron.schedule('winsquad-resolve-rounds', '* * * * *',
--                             $$select public.resolve_due_rounds()$$);
--      NOTE: pg_cron is minute-granularity, so a round whose 30s window ends
--      may wait up to ~60s for the cron resolver. This is acceptable for v1.
--      As a backstop, get_current_round() and place_bid() opportunistically
--      resolve due rounds on every call, so the game keeps moving on traffic.
--   3. After your first phone-OTP sign-in, make yourself admin (SQL Editor):
--        insert into public.admins (user_id)
--        values ('PASTE-YOUR-auth.users-UUID-HERE');
--      (Find your UUID in Authentication > Users.)
--
-- FRONTEND CONTRACT (RPC functions — exact names/signatures, do not rename)
--   get_current_round() -> public_rounds row (open 30s round; creates one if none)
--   place_bid(p_round_id uuid, p_amount numeric, p_is_free boolean default false) -> jsonb
--   resolve_round(p_round_id uuid) -> jsonb
--   resolve_due_rounds() -> jsonb
--   transfer_funds(p_to_transfer_id text, p_amount numeric) -> jsonb
--   claim_daily_streak() -> jsonb {ok, streak_day, amount}
--   apply_referral(p_referral_id text) -> jsonb
--   create_private_table() -> jsonb {ok, table_id, code}
--   join_private_table(p_code text) -> jsonb
--   place_private_bid(p_table_id uuid, p_amount numeric) -> jsonb
--   approve_deposit(p_txn_id uuid) -> jsonb   (admin / service_role only)
--   reject_deposit(p_txn_id uuid)  -> jsonb   (admin / service_role only)
--   update_display_name(p_name text) -> jsonb (helper, not in original spec)
--   is_admin() -> boolean                     (helper)
--
-- CLIENT DATA RULES (the frontend MUST follow these)
--   * NEVER query public.rounds directly — rounds.fee_amount is the hidden 10%
--     company cut. Use the public_rounds VIEW (fee column excluded) or
--     get_current_round(). There is intentionally NO select policy on rounds.
--   * Live round updates: subscribe via Realtime to public.round_stats
--     (NOT to bids — other players' bid amounts stay hidden by design).
--   * Leaderboard/results: query public.round_results (winners only; losers are
--     never exposed) and join public.public_profiles for display names.
--   * All timestamps are timestamptz. "Calendar day" rules (free bid, streak)
--     use Asia/Karachi (PKT) server-side.
--   * Deposits are MANUAL: client INSERTs a transactions row
--     (type='deposit', status='pending', method, external_txn_id), then an
--     admin marks it completed via approve_deposit(), which credits the wallet.
--
-- ============================================================================

